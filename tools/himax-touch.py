#!/usr/bin/env python3
"""
A22's touch screen in iOS: the loader loads the Himax's firmware before jumping to XNU, and a new
driver in XNU (bsd/dev/redwood_himax.c, boot-arg touchscreen=3) reads the fingers and passes them to iOS.

  python3 himax-touch.py ~/dev/hakios          -> only checks
  python3 himax-touch.py ~/dev/hakios apply    -> applies (saves *.touch.orig the first time)

Needs himax-probe.py applied first (mtkloader.c with HIMAX_PROBE) and mtkloader/himaxfw.h
(generated by tools/himax-probe-a22.sh with HIMAX_FW=1, or: python3 mkhimaxfw.py <bin> > mtkloader/himaxfw.h).
Copies mtkhimax.h and redwood_himax.c (next to this script) into place.
"""
import os
import shutil
import sys

XNU = "xnu-src/xnu-8796.121.2"

CAMBIOS = {
    "mtkloader/mtkloader.c": [
        ('#if HIMAX_PROBE\n#include "mtkhimax.h"\n#endif\n',
         '#ifndef HIMAX_TOUCH                    /* A22: Himax touch controller for XNU if himaxfw.h exists */\n'
         '#if __has_include("himaxfw.h")\n#define HIMAX_TOUCH 1\n#else\n#define HIMAX_TOUCH 0\n#endif\n#endif\n'
         '#if HIMAX_PROBE || HIMAX_TOUCH\n#include "mtkhimax.h"\n#endif\n'),
        ("#if HIMAX_PROBE\nstatic void himax_hand_back(void);\n#endif\n",
         "#if HIMAX_PROBE || HIMAX_TOUCH\nstatic void himax_hand_back(void);\n#endif\n"),
        ("#if HIMAX_PROBE\n\thimax_hand_back();\n#endif\n",
         "#if HIMAX_PROBE || HIMAX_TOUCH\n\thimax_hand_back();\n#endif\n"),
        ("\ttouch_bring_up();\n#endif\n",
         "\ttouch_bring_up();\n#endif\n#if HIMAX_TOUCH\n\thimax_bring_up();      /* A22: the touch controller, before XNU */\n#endif\n"),
    ],
    XNU + "/bsd/conf/files": [
        ("bsd/dev/redwood_tcm.c\tstandard\n",
         "bsd/dev/redwood_tcm.c\tstandard\nbsd/dev/redwood_himax.c\tstandard\n"),
    ],
    XNU + "/bsd/sys/redwood_input.h": [
        ("void redwood_tcm_init(void);",
         "void redwood_himax_init(void);          /* boot-arg touchscreen=3: the A22's Himax HX83112F */\n"
         "void redwood_tcm_init(void);"),
    ],
    XNU + "/bsd/dev/redwood_input.c": [
        ("\tredwood_tcm_init();\n", "\tredwood_tcm_init();\n\tredwood_himax_init();\n"),
    ],
}

COPIAS = [("mtkhimax.h", "mtkloader/mtkhimax.h"), ("redwood_himax.c", XNU + "/bsd/dev/redwood_himax.c")]


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    raiz = os.path.expanduser(sys.argv[1])
    aplicar = len(sys.argv) > 2 and sys.argv[2] in ("apply", "aplicar")
    aqui = os.path.dirname(os.path.abspath(__file__))
    for origen, _ in COPIAS:
        if not os.path.isfile(os.path.join(aqui, origen)):
            raise SystemExit("%s is missing next to this script" % origen)
    if not os.path.isfile(os.path.join(raiz, "mtkloader", "himaxfw.h")):
        print("WARNING: mtkloader/himaxfw.h is missing; without it the loader does not load the touch controller")
    nuevos = {}
    faltan = 0
    for rel, cambios in CAMBIOS.items():
        ruta = os.path.join(raiz, rel)
        if not os.path.isfile(ruta):
            print("MISSING    |", rel)
            faltan += 1
            continue
        texto = open(ruta, encoding="utf-8").read()
        for viejo, nuevo in cambios:
            if nuevo in texto:
                print("was there  |", rel, "|", nuevo.strip().splitlines()[0][:60])
                continue
            n = texto.count(viejo)
            if n != 1:
                print("NOT FOUND (%d times) |" % n, rel, "|", viejo.strip().splitlines()[0][:60])
                faltan += 1
                continue
            texto = texto.replace(viejo, nuevo)
            print("changes    |", rel, "|", nuevo.strip().splitlines()[0][:60])
        nuevos[ruta] = texto
    if faltan:
        raise SystemExit("\n%d change(s) do not fit: touching nothing. Send me this output." % faltan)
    if not aplicar:
        print("\nEverything fits. To apply it: python3 himax-touch.py %s apply" % sys.argv[1])
        return
    for ruta, texto in nuevos.items():
        if not os.path.exists(ruta + ".touch.orig"):
            shutil.copy2(ruta, ruta + ".touch.orig")
        open(ruta, "w", encoding="utf-8").write(texto)
    for origen, destino in COPIAS:
        shutil.copy2(os.path.join(aqui, origen), os.path.join(raiz, destino))
        print("copied     |", destino)
    print("\nApplied. Now: ./xnu-build.sh -j8 -k, rebuild the payload and XNU_ARGS with touchscreen=3")


if __name__ == "__main__":
    main()
